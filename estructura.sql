CREATE TABLE clientes (cliente_id serial primary key,
nombre varchar (100) not null, 
email varchar (100) unique,
barrio varchar (100), 
fecha_registro date);
CREATE TABLE productos (producto_id serial primary key,
nombre varchar (100) not null,
categoria varchar (50) not null,
precio numeric(10,2) check (precio > 0),
medida_ml integer check (medida_ml > 0),
shots_espresso integer check (shots_espresso >= 0)
);
CREATE TABLE pedidos (pedido_id serial primary key,
cliente_id integer references clientes (cliente_id), 
producto_id integer not null references productos(producto_id), 
fecha_pedido date,
cantidad integer not null check (cantidad >0));

